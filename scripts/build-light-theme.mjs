// Generates client/src/theme-light.css from client/src/styles.css.
// Every color's HSL lightness is inverted (hue and saturation kept), so the dark theme's contrast
// pairs carry over: dark surfaces become light, light text becomes dark, the lime accent a deep green.
// Rules are scoped to :root[data-theme="light"]; the dark theme itself is untouched.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const source = fileURLToPath(new URL('../client/src/styles.css', import.meta.url));
const target = fileURLToPath(new URL('../client/src/theme-light.css', import.meta.url));
const SCOPE = ':root[data-theme="light"]';

function invert(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min; s = l > .5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4; h /= 6;
  }
  const L = 1 - l; // the inversion
  if (!s) { const v = Math.round(L * 255); return [v, v, v]; }
  const q = L < .5 ? L * (1 + s) : L + s - L * s, p = 2 * L - q;
  const hue = t => { t = (t + 1) % 1; return t < 1 / 6 ? p + (q - p) * 6 * t : t < .5 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p; };
  return [hue(h + 1 / 3), hue(h), hue(h - 1 / 3)].map(v => Math.round(v * 255));
}
const hex = n => n.toString(16).padStart(2, '0');
function convertColors(value) {
  return value
    .replace(/#([0-9a-f]{3,8})\b/gi, (match, digits) => {
      if (![3, 4, 6, 8].includes(digits.length)) return match;
      const full = digits.length <= 4 ? [...digits].map(c => c + c).join('') : digits;
      const [r, g, b] = invert(...[0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16)));
      return `#${hex(r)}${hex(g)}${hex(b)}${full.length === 8 ? full.slice(6) : ''}`;
    })
    .replace(/rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*([,/]\s*[\d.]+%?)?\s*\)/gi, (_match, r, g, b, alpha) => {
      const [nr, ng, nb] = invert(+r, +g, +b);
      return alpha ? `rgba(${nr}, ${ng}, ${nb}${alpha.replace('/', ',')})` : `rgb(${nr}, ${ng}, ${nb})`;
    })
    .replace(/(^|[\s:,(])(white|black)(?=[\s;,)]|$)/gi, (_m, pre, name) => pre + (name.toLowerCase() === 'white' ? '#000000' : '#ffffff'));
}
const COLOR = /#[0-9a-f]{3,8}\b|rgba?\(|\b(white|black)\b/i;
const scope = selector => selector.split(',').map(part => {
  const s = part.trim();
  if (!s) return s;
  if (s.startsWith(':root')) return s.replace(':root', SCOPE);
  if (/^(html)\b/.test(s)) return s.replace(/^html/, `html${SCOPE.slice(5)}`);
  return `${SCOPE} ${s}`;
}).join(', ');

// Tiny CSS walker: handles comments, @media/@supports nesting; skips @keyframes and @font-face.
function walk(css) {
  let out = '', i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) { i = css.indexOf('*/', i + 2) + 2; continue; }
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    for (; j < css.length && depth; j++) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; }
    const body = css.slice(open + 1, j - 1);
    i = j;
    if (/^@(keyframes|-webkit-keyframes|font-face|import)/.test(head)) continue;
    if (/^@(media|supports)/.test(head)) { const inner = walk(body); if (inner.trim()) out += `${head} {\n${inner}}\n`; continue; }
    if (head.startsWith('@')) continue;
    if (head.includes('theme-swatch')) continue; // theme previews keep their real colors
    const declarations = body.split(';').map(d => d.trim()).filter(d => d && COLOR.test(d.split(':').slice(1).join(':')) && !/^--mono|^font-family/.test(d));
    if (declarations.length) out += `${scope(head)} { ${declarations.map(d => { const k = d.indexOf(':'); return `${d.slice(0, k)}:${convertColors(d.slice(k + 1))}`; }).join('; ')}; }\n`;
  }
  return out;
}
// Drop @import/@charset statements (no braces) so they don't swallow the next rule.
const css = readFileSync(source, 'utf8').replace(/@(import|charset)[^;]*;/g, '');
writeFileSync(target, `/* GENERATED by scripts/build-light-theme.mjs from styles.css. Do not edit by hand. */\n${SCOPE} { color-scheme: light; }\n${walk(css)}`);
console.log('theme-light.css written');
